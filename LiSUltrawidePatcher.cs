        private const string SteamAppId = "1874000";
        private const string GameDirName = "LifeIsStrangeDoubleExposure";
        private const string ExeName = "Chronos-Win64-Shipping.exe";
        private static readonly string ExeRelative =
            Path.Combine("Chronos", "Binaries", "Win64", ExeName);

        private static string ExeUnder(string gameRoot)
        {
            if (string.IsNullOrEmpty(gameRoot)) return null;
            try
            {
                string p = Path.GetFullPath(Path.Combine(gameRoot, ExeRelative));
                return File.Exists(p) ? p : null;
            }
            catch { return null; }
        }

        private static bool LooksLikeGame(string name)
        {
            StringBuilder flat = new StringBuilder();
            foreach (char c in name.ToLowerInvariant())
                if (char.IsLetterOrDigit(c)) flat.Append(c);
            return flat.ToString().Contains("doubleexposure");
        }

        private static string ReadTextFile(string path)
        {
            try { return File.ReadAllText(path); }
            catch { return ""; }
        }

        private static List<string> FixedDrives()
        {
            List<string> drives = new List<string>();
            try
            {
                foreach (DriveInfo d in DriveInfo.GetDrives())
                    if (d.DriveType == DriveType.Fixed && d.IsReady)
                        drives.Add(d.RootDirectory.FullName);
            }
            catch { }
            if (drives.Count == 0) drives.Add("C:\\");
            return drives;
        }

        private static void AddDir(List<string> list, string path)
        {
            if (string.IsNullOrEmpty(path)) return;
            try
            {
                if (!Directory.Exists(path)) return;
                // normalise, so C:/steam and C:\Steam are not scanned twice
                path = Path.GetFullPath(path);
            }
            catch { return; }
            string key = path.TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar);
            foreach (string existing in list)
                if (string.Equals(existing.TrimEnd(Path.DirectorySeparatorChar,
                                                Path.AltDirectorySeparatorChar), key,
                                  StringComparison.OrdinalIgnoreCase))
                    return;
            list.Add(path);
        }

        private static string RegistryValue(RegistryKey hive, string key, string name)
        {
            try
            {
                using (RegistryKey k = hive.OpenSubKey(key))
                    return (k == null) ? null : k.GetValue(name) as string;
            }
            catch { return null; }
        }

        // every Steam installation, plus each library folder it has registered
        private static List<string> SteamLibraries()
        {
            List<string> installs = new List<string>();
            AddDir(installs, RegistryValue(Registry.CurrentUser,
                                           "Software\\Valve\\Steam", "SteamPath"));
            AddDir(installs, RegistryValue(Registry.LocalMachine,
                                           "SOFTWARE\\WOW6432Node\\Valve\\Steam", "InstallPath"));
            AddDir(installs, RegistryValue(Registry.LocalMachine,
                                           "SOFTWARE\\Valve\\Steam", "InstallPath"));
            foreach (string drive in FixedDrives())
            {
                AddDir(installs, Path.Combine(drive, "Program Files (x86)\\Steam"));
                AddDir(installs, Path.Combine(drive, "Program Files\\Steam"));
                AddDir(installs, Path.Combine(drive, "Steam"));
            }

            List<string> libraries = new List<string>(installs);
            foreach (string install in installs)
            {
                string vdf = Path.Combine(install, "steamapps\\libraryfolders.vdf");
                if (!File.Exists(vdf)) continue;
                string text = ReadTextFile(vdf);
                // current format keys each entry "path"; the pre-2021 one used numbers
                foreach (string pattern in new[] { "\"path\"\\s*\"([^\"]+)\"",
                                                   "\"[0-9]+\"\\s*\"([^\"]{3,})\"" })
                    foreach (Match m in Regex.Matches(text, pattern))
                        AddDir(libraries, m.Groups[1].Value.Replace("\\\\", "\\"));
            }
            return libraries;
        }

        /// <summary>The game executable, wherever it is; source says how it was found.</summary>
        private static string FindGameExe(out string source)
        {
            source = null;

            // 1. beside this tool, or beside the folder it was started from
            string[] relatives = { ExeName, ExeRelative,
                                   Path.Combine("..", ExeRelative),
                                   Path.Combine("..", "..", ExeRelative) };
            string[] bases = { AppDomain.CurrentDomain.BaseDirectory,
                               Directory.GetCurrentDirectory() };
            foreach (string dir in bases)
                foreach (string rel in relatives)
                {
                    string full;
                    try { full = Path.GetFullPath(Path.Combine(dir, rel)); }
                    catch { continue; }
                    if (File.Exists(full)) { source = "the folder it was run from"; return full; }
                }

            // 2. every Steam library on the machine
            foreach (string library in SteamLibraries())
            {
                string apps = Path.Combine(library, "steamapps");
                string common = Path.Combine(apps, "common");
                if (!Directory.Exists(common)) continue;
                List<string> names = new List<string>();
                string manifest = Path.Combine(apps, "appmanifest_" + SteamAppId + ".acf");
                if (File.Exists(manifest))
                {
                    Match m = Regex.Match(ReadTextFile(manifest),
                                          "\"installdir\"\\s*\"([^\"]+)\"");
                    if (m.Success) names.Add(m.Groups[1].Value);
                }
                names.Add(GameDirName);
                try
                {
                    foreach (string d in Directory.GetDirectories(common))
                        if (LooksLikeGame(Path.GetFileName(d))) names.Add(Path.GetFileName(d));
                }
                catch { }
                foreach (string name in names)
                {
                    string hit = ExeUnder(Path.Combine(common, name));
                    if (hit != null) { source = "Steam library " + library; return hit; }
                }
            }

            // 3. whatever the Epic Games Launcher has installed
            try
            {
                string manifests = Path.Combine(
                    Environment.GetFolderPath(Environment.SpecialFolder.CommonApplicationData),
                    "Epic\\EpicGamesLauncher\\Data\\Manifests");
                foreach (string item in Directory.GetFiles(manifests, "*.item"))
                {
                    Match m = Regex.Match(ReadTextFile(item),
                                          "\"InstallLocation\"\\s*:\\s*\"([^\"]+)\"");
                    if (!m.Success) continue;
                    string hit = ExeUnder(m.Groups[1].Value.Replace("\\\\", "\\"));
                    if (hit != null) { source = "the Epic Games Launcher"; return hit; }
                }
            }
            catch { }

            // 4. the usual places a game folder ends up when no launcher claims it
            string[] commonRoots = { "Games", "Program Files", "Program Files (x86)",
                                     "GOG Games", "Epic Games",
                                     "SteamLibrary\\steamapps\\common",
                                     "Games\\steamapps\\common" };
            foreach (string drive in FixedDrives())
            {
                List<string> roots = new List<string> { drive };
                foreach (string rel in commonRoots) roots.Add(Path.Combine(drive, rel));
                foreach (string root in roots)
                {
                    string hit = ExeUnder(Path.Combine(root, GameDirName));
                    if (hit != null) { source = root; return hit; }
                    string[] entries;
                    try { entries = Directory.GetDirectories(root); }
                    catch { continue; }
                    foreach (string entry in entries)
                    {
                        if (!LooksLikeGame(Path.GetFileName(entry))) continue;
                        hit = ExeUnder(entry);
                        if (hit != null) { source = root; return hit; }
                    }
                }
            }
            return null;
        }

        private void AutoDetect()
        {
            // executable: beside this tool, then Steam, Epic and the usual roots
            string source;
            string exe = FindGameExe(out source);
            if (exe != null)
            {
                txtExePath.Text = exe;
                Log("Found game via " + source);
            }
            else
            {
                Log("Could not find the game automatically - use Browse.");
            }

            // resolution: select the preset matching this display, else Custom
            Rectangle b = Screen.PrimaryScreen.Bounds;
            txtWidth.Text = b.Width.ToString();
            txtHeight.Text = b.Height.ToString();
            int match = -1;
            for (int i = 0; i < presets.Count; i++)
                if (presets[i].W == b.Width && presets[i].H == b.Height) { match = i; break; }
            cmbPresets.SelectedIndex = (match >= 0) ? match : presets.Count;
            Log(string.Format("Detected display: {0}x{1}{2}", b.Width, b.Height,
                              match >= 0 ? "" : "  (using Custom)"));

            // show the start of the path rather than opening mid-selection
            txtExePath.SelectionLength = 0;
            txtExePath.SelectionStart = 0;
            ActiveControl = btnInstall;
        }

