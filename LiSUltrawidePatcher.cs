        private void StartExeCheck()
        {
            if (!IsHandleCreated) return;
            string path = txtExePath.Text.Trim();
            int token = ++checkToken;

            if (path.Length == 0)
            {
                SetExeStatus("", SystemColors.GrayText, "No executable selected.", null);
                SetFilesStatus("", SystemColors.GrayText, "", null);
                return;
            }
            if (!File.Exists(path))
            {
                SetExeStatus(GlyphWarn, WarnColor, "There is no file at that path.", path);
                SetFilesStatus("", SystemColors.GrayText, "", null);
                return;
            }
            SetExeStatus("", SystemColors.GrayText,
                         "Checking " + Path.GetFileName(path) + "...", path);
            SetFilesStatus("", SystemColors.GrayText, "", null);

            ThreadPool.QueueUserWorkItem(delegate
            {
                string status, detail, files, filesDetail;
                RunCheck(path, out status, out detail, out files, out filesDetail);
                if (token != checkToken) return;             // superseded
                try
                {
                    BeginInvoke((MethodInvoker)delegate
                    {
                        if (token != checkToken) return;
                        ApplyStatus(status, detail);
                        ApplyFilesStatus(files, filesDetail);
                    });
                }
                catch { }                                    // form already gone
            });
        }

        /// <summary>The full-width UI container: is it there, and is it current?</summary>
        private void ApplyFilesStatus(string status, string detail)
        {
            switch (status)
            {
                case "current":
                    SetFilesStatus(GlyphOk, OkColor, "Full-width UI " + detail + ".", detail);
                    break;
                case "stale":
                    SetFilesStatus(GlyphWarn, WarnColor,
                                   "Full-width UI was built for a different build of the "
                                   + "game - Install again before playing.", detail);
                    break;
                case "unrecorded":
                case "incomplete":
                    SetFilesStatus(GlyphWarn, WarnColor,
                                   "Full-width UI needs installing again.", detail);
                    break;
                case "none":
                    SetFilesStatus("", SystemColors.GrayText,
                                   "Full-width UI is not installed.", detail);
                    break;
                default:
                    SetFilesStatus("", SystemColors.GrayText, "", detail);
                    break;
            }
        }

        private void ApplyStatus(string status, string detail)
        {
            switch (status)
            {
                case "original":
                    SetExeStatus(GlyphOk, OkColor,
                                 "Original executable - a build this patcher knows.", detail);
                    break;
                case "patched":
                    SetExeStatus(GlyphWarn, WarnColor,
                                 "Already patched - Install re-applies from the backup.",
                                 detail);
                    break;
                case "unknown":
                    SetExeStatus(GlyphWarn, WarnColor,
                                 "Unrecognised executable - a game update, or the wrong file.",
                                 detail);
                    break;
                case "missing":
                    SetExeStatus(GlyphWarn, WarnColor, "There is no file at that path.", detail);
                    break;
                case "norunner":
                    SetExeStatus("", SystemColors.GrayText,
                                 "Not checked - no Python found yet.",
                                 "Install or Restore still works: it fetches a private "
                                 + "Python if this machine has none.");
                    break;
                case "noscript":
                    SetExeStatus("", SystemColors.GrayText,
                                 "Not checked - patcher.py is not next to this program.", null);
                    break;
                default:
                    SetExeStatus("", SystemColors.GrayText, "Could not check this file.", detail);
                    break;
            }
        }

        /// <summary>patcher.py --check-exe, out of sight; never prompts.</summary>
        private void RunCheck(string path, out string status, out string detail,
                              out string files, out string filesDetail)
        {
            status = "error";
            detail = null;
            files = "error";
            filesDetail = null;
            string script = ScriptPath();
            if (script == null) { status = "noscript"; return; }

            List<string> argv = new List<string>();
            argv.Add("--check-exe");
            argv.Add("--exe");
            argv.Add("\"" + path + "\"");

            // Every runner in turn: one that cannot start Python at all must not
            // be the reason the badge says "could not check" while the next one
            // in the list would have answered.
            List<Runner> runners = Runners(script, argv, uvCheckAllowed);
            if (runners.Count == 0) { status = "norunner"; return; }

            foreach (Runner r in runners)
            {
                try
                {
                    using (Process p = Process.Start(Launch(r, script)))
                    {
                        // drained on its own thread: a runner that writes a
                        // long complaint to stderr would otherwise fill its
                        // pipe and hang while we read the other one
                        Process capture = p;
                        ThreadPool.QueueUserWorkItem(delegate
                        {
                            try { capture.StandardError.ReadToEnd(); }
                            catch { }
                        });
                        string text = p.StandardOutput.ReadToEnd();
                        p.WaitForExit();
                        bool answered = false;
                        foreach (string line in text.Split('\n'))
                        {
                            string t = line.Trim();
                            if (t.StartsWith("status: "))
                            {
                                status = t.Substring(8).Trim();
                                answered = true;
                            }
                            else if (t.StartsWith("detail: ")) detail = t.Substring(8).Trim();
                            else if (t.StartsWith("files: ")) files = t.Substring(7).Trim();
                            else if (t.StartsWith("filesdetail: "))
                                filesDetail = t.Substring(13).Trim();
                        }
                        if (answered) return;
                    }
                }
                catch (Exception ex)
                {
                    status = "error";
                    detail = ex.Message;
                }
            }
        }

        protected override void OnShown(EventArgs e)
        {
            base.OnShown(e);
            StartExeCheck();
        }

        // A machine with no Python at all still has to work.  Preference order is
        // uv (fastest, and it brings the compiled blake3), then whatever Python
        // is installed, then a private copy of python.org's embeddable build
        // unpacked into tools/python - ~11 MB to download, ~22 MB on disk, no
        // installer, no PATH changes, and it is deleted along with this fix.
        private const string PythonEmbedUrl =
            "https://www.python.org/ftp/python/3.12.10/python-3.12.10-embed-amd64.zip";

        /// <summary>Where a private interpreter may live, best place first.</summary>
        private static List<string> EmbeddedPythonDirs()
        {
            List<string> dirs = new List<string>();
            dirs.Add(Path.Combine(AppDomain.CurrentDomain.BaseDirectory,
                                  Path.Combine("tools", "python")));
            // the fix may have been unpacked somewhere unwritable - Program
            // Files, a shared drive - so keep a per-user location in reserve
            string local = Environment.GetFolderPath(
                Environment.SpecialFolder.LocalApplicationData);
            if (!string.IsNullOrEmpty(local))
                dirs.Add(Path.Combine(local, Path.Combine("LiSUltrawideFix", "python")));
            return dirs;
        }

        private static string EmbeddedPython()
        {
            foreach (string dir in EmbeddedPythonDirs())
            {
                string exe = Path.Combine(dir, "python.exe");
                if (File.Exists(exe)) return exe;
            }
            return null;
        }

        /// <summary>Can a file actually be created in there?</summary>
        private static bool Writable(string dir)
        {
            try
            {
                Directory.CreateDirectory(dir);
                string probe = Path.Combine(dir, ".write-probe");
                using (File.Create(probe)) { }
                File.Delete(probe);
                return true;
            }
            catch { return false; }
        }

        /// <summary>Fetch python.org's embeddable build into tools/python.</summary>
        private string FetchEmbeddedPython()
        {
            string dir = null;
            foreach (string candidate in EmbeddedPythonDirs())
            {
                if (Writable(candidate)) { dir = candidate; break; }
                Log("Cannot write to " + candidate + " - trying elsewhere.");
            }
            if (dir == null)
            {
                Log("No writable place to put an interpreter.");
                return null;
            }
            string zip = Path.Combine(Path.GetTempPath(), "lisde-python-embed.zip");
            try
            {
                Log("No Python on this machine - fetching a private copy (~11 MB):");
                Log("  " + PythonEmbedUrl);
                Log("  into " + dir);
                Application.DoEvents();
                // the 4.0 default protocol list predates TLS 1.2, which python.org requires
                ServicePointManager.SecurityProtocol = (SecurityProtocolType)3072;
                using (WebClient wc = new WebClient())
                {
                    wc.Headers.Add("User-Agent", "LiSUltrawideFix");
                    wc.DownloadFile(PythonEmbedUrl, zip);
                }
                if (Directory.Exists(dir)) Directory.Delete(dir, true);
                Directory.CreateDirectory(dir);
                ZipFile.ExtractToDirectory(zip, dir);
                string exe = Path.Combine(dir, "python.exe");
                if (!File.Exists(exe))
                {
                    Log("  the archive contained no python.exe");
                    return null;
                }
                Log("  Python ready: " + exe);
                return exe;
            }
            catch (Exception ex)
            {
                Log("  could not fetch Python: " + ex.Message);
                return null;
            }
            finally
            {
                try { if (File.Exists(zip)) File.Delete(zip); }
                catch { }
            }
        }

        /// <summary>uv from PATH, or from the locations its installer uses.</summary>
        private static string FindUv()
        {
            string onPath = Which("uv");
            if (onPath != null) return onPath;
            // A freshly installed uv is not on THIS process's PATH, which was
            // captured at launch - so look where the installer puts it.
            string home = Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);
            string[] dirs = {
                Path.Combine(home, ".local", "bin"),
                Path.Combine(home, ".cargo", "bin"),
            };
            foreach (string d in dirs)
            {
                try
                {
                    string f = Path.Combine(d, "uv.exe");
                    if (File.Exists(f)) return f;
                }
                catch { }
            }
            return null;
        }

        /// <summary>One way of running patcher.py, in preference order.</summary>
        private struct Runner
        {
            public string Exe, Args, Label;
            public Runner(string exe, string args, string label)
            {
                Exe = exe; Args = args; Label = label;
            }
        }

        /// <summary>Every way this machine can run the script, best first.</summary>
        //
        // uv is first because it brings its own interpreter and the compiled
        // blake3 - but it needs the network to do so, so a machine that is
        // offline, or behind a proxy, gets nothing from it. That is why this
        // returns a LIST: Run() falls through to the next entry when a runner
        // fails before the patcher itself ever printed anything.
        private List<Runner> Runners(string script, List<string> argv, bool allowUv)
        {
            StringBuilder tail = new StringBuilder();
            tail.Append('"').Append(script).Append('"');
            foreach (string a in argv) tail.Append(' ').Append(a);

            List<Runner> list = new List<Runner>();
            string uv = allowUv ? FindUv() : null;
            if (uv != null)
                list.Add(new Runner(uv, "run --quiet --script " + tail, "uv"));
            string py = Which("py");
            if (py != null) list.Add(new Runner(py, "-3 " + tail, "the Python launcher"));
            string python = Which("python");
            if (python != null) list.Add(new Runner(python, tail.ToString(), "Python"));
            string embedded = EmbeddedPython();
            if (embedded != null)
                list.Add(new Runner(embedded, tail.ToString(), "the private Python"));
            return list;
        }

        /// <summary>Start settings shared by every way of running the script.</summary>
        //
        // The encodings matter: without them the child writes in the machine's
        // ANSI code page while this process reads the OEM one, so a game path
        // with a non-ASCII character in it arrives as mojibake - and Python
        // raises UnicodeEncodeError rather than printing it at all. UTF-8 on
        // both sides is the only pair that agrees on every Windows.
        // Both streams are always redirected: .NET refuses to start a process
        // that carries an encoding for a stream it is not capturing, so setting
        // one without the other throws instead of running anything.
        private static ProcessStartInfo Launch(Runner r, string script)
        {
            ProcessStartInfo psi = new ProcessStartInfo(r.Exe, r.Args);
            psi.UseShellExecute = false;
            psi.CreateNoWindow = true;
            psi.RedirectStandardOutput = true;
            psi.RedirectStandardError = true;
            psi.StandardOutputEncoding = new UTF8Encoding(false);
            psi.StandardErrorEncoding = new UTF8Encoding(false);
            psi.EnvironmentVariables["PYTHONUTF8"] = "1";
            psi.EnvironmentVariables["PYTHONIOENCODING"] = "utf-8";
            psi.WorkingDirectory = Path.GetDirectoryName(script);
            return psi;
        }

        private static string Which(string name)
        {
            string path = Environment.GetEnvironmentVariable("PATH");
            if (path == null) return null;
            foreach (string dir in path.Split(';'))
            {
                if (dir.Length == 0) continue;
                foreach (string ext in new[] { ".exe", ".cmd", ".bat" })
                {
                    try
                    {
                        string f = Path.Combine(dir.Trim('"'), name + ext);
                        if (File.Exists(f) && !IsStoreAlias(f)) return f;
                    }
                    catch { }
                }
            }
            return null;
        }

        /// <summary>Is this the Microsoft Store's python.exe placeholder?</summary>
        //
        // Windows ships zero-byte "app execution aliases" in WindowsApps, and
        // python.exe is one of them on a machine that has never installed
        // Python. It is a real file, so File.Exists says yes; running it opens
        // the Store and exits without doing anything. Taking it for an
        // interpreter is exactly how a clean PC ends up unable to install.
        private static bool IsStoreAlias(string file)
        {
            if (file.IndexOf("\\WindowsApps\\", StringComparison.OrdinalIgnoreCase) >= 0)
                return true;
            try
            {
                return new FileInfo(file).Length == 0;
            }
            catch { return false; }
        }

        private string ScriptPath()
        {
            string baseDir = AppDomain.CurrentDomain.BaseDirectory;
            string p = Path.Combine(baseDir, "patcher.py");
            return File.Exists(p) ? p : null;
        }

        private void Run(List<string> argv)
        {
            string script = ScriptPath();
            if (script == null)
            {
                MessageBox.Show("patcher.py must sit next to this program.",
                                "Missing patcher.py", MessageBoxButtons.OK,
                                MessageBoxIcon.Error);
                return;
            }
            List<Runner> runners = Runners(script, argv, true);
            if (runners.Count == 0)
            {
                txtLog.Clear();
                if (FetchEmbeddedPython() == null)
                {
                    MessageBox.Show(
                        "Nothing to run the patcher with, and the interpreter "
                        + "download failed.\r\n\r\n"
                        + "Check the connection and try again, or install Python "
                        + "3.8+ (python.org) and make sure it is on PATH.",
                        "No Python", MessageBoxButtons.OK, MessageBoxIcon.Error);
                    return;
                }
                runners = Runners(script, argv, true);
                if (runners.Count == 0) return;
            }

            btnInstall.Enabled = btnRestore.Enabled = false;
            txtLog.Clear();
            RunWith(runners, 0, script, argv);
        }

        /// <summary>Anything the patcher prints starts with this banner.</summary>
        private const string BannerMark = "Ultrawide Fix v";

        // The one thing this program must never do is decide on its own to run
        // an install twice. Falling through to the next runner is safe only
        // because the banner above is the patcher's first line: no banner means
        // the interpreter never got as far as the script, so nothing was
        // written and re-running from scratch cannot stack anything.
        private void RunWith(List<Runner> runners, int index, string script,
                             List<string> argv)
        {
            Runner r = runners[index];
            Log("> " + r.Exe + " " + r.Args);
            Log("");

            ProcessStartInfo psi = Launch(r, script);

            bool started = false;         // did the patcher itself ever speak?
            bool denied = false;          // ...and was it a permissions refusal?
            Process proc = new Process();
            proc.StartInfo = psi;
            proc.EnableRaisingEvents = true;
            DataReceivedEventHandler onLine = delegate(object s, DataReceivedEventArgs e)
            {
                if (e.Data == null) return;
                if (e.Data.IndexOf(BannerMark, StringComparison.Ordinal) >= 0)
                    started = true;
                // both patcher.py and the UI-layout step end that advice this
                // way ("run this installer as administrator" / "run the
                // installer as administrator")
                if (e.Data.IndexOf("as administrator",
                                   StringComparison.OrdinalIgnoreCase) >= 0)
                    denied = true;
                Log(e.Data);
            };
            proc.OutputDataReceived += onLine;
            proc.ErrorDataReceived += onLine;
            proc.Exited += delegate
            {
                int code = proc.ExitCode;
                BeginInvoke((MethodInvoker)delegate
                {
                    if (code != 0 && !started && index + 1 < runners.Count)
                    {
                        Log("");
                        Log(r.Label + " could not start the patcher (exit code "
                            + code + ") - trying " + runners[index + 1].Label + ".");
                        Log("");
                        RunWith(runners, index + 1, script, argv);
                        return;
                    }
                    Log("");
                    Log(code == 0 ? "Finished." : "Failed (exit code " + code + ").");
                    btnInstall.Enabled = btnRestore.Enabled = true;
                    uvCheckAllowed = true;     // whatever runs the patcher is primed now
                    StartExeCheck();           // the executable just changed
                    if (code != 0 && denied) OfferElevation(r, script);
                });
            };
            try
            {
                proc.Start();
                proc.BeginOutputReadLine();
                proc.BeginErrorReadLine();
            }
            catch (Exception ex)
            {
                Log("Could not start " + r.Exe + ": " + ex.Message);
                if (index + 1 < runners.Count)
                {
                    Log("Trying " + runners[index + 1].Label + ".");
                    Log("");
                    RunWith(runners, index + 1, script, argv);
                    return;
                }
                btnInstall.Enabled = btnRestore.Enabled = true;
            }
        }

        // A game under Program Files - Steam's default - cannot be written by an
        // ordinary process, and "right-click, Run as administrator" is not
        // something this program can assume anyone knows. So it offers, and
        // repeats the exact same command with the elevation prompt attached.
        private void OfferElevation(Runner r, string script)
        {
            if (MessageBox.Show(
                    "Windows refused permission to write the game files.\r\n\r\n"
                    + "This happens when the game is installed under Program "
                    + "Files. Run the same install again as administrator?",
                    "Administrator rights needed", MessageBoxButtons.YesNo,
                    MessageBoxIcon.Question) != DialogResult.Yes)
                return;
            RunElevated(r, script);
        }

        /// <summary>The same command, elevated, with its output in a file.</summary>
        //
        // An elevated child cannot have its pipes redirected (that needs
        // UseShellExecute = false, which in turn cannot request elevation), so
        // it is run through cmd with its output sent to a temporary file, which
        // is poured into the log when it finishes.
        private void RunElevated(Runner r, string script)
        {
            string log = Path.Combine(Path.GetTempPath(), "lisde-elevated.log");
            try { if (File.Exists(log)) File.Delete(log); }
            catch { }

            // Elevation can land in a different account - a standard user who
            // types an administrator's password gets that administrator's
            // profile - and then %LOCALAPPDATA% is the wrong one: Engine.ini
            // would be written where the game will never read it. It is the
            // invoking user's, so pass theirs through.
            string local = Environment.GetFolderPath(
                Environment.SpecialFolder.LocalApplicationData);
            string keepLocal = string.IsNullOrEmpty(local)
                ? "" : "set \"LOCALAPPDATA=" + local + "\"&& ";
            string command = "set PYTHONUTF8=1&& set PYTHONIOENCODING=utf-8&& "
                             + keepLocal
                             + "\"" + r.Exe + "\" " + r.Args
                             + " > \"" + log + "\" 2>&1";
            ProcessStartInfo psi = new ProcessStartInfo("cmd.exe", "/c \"" + command + "\"");
            psi.UseShellExecute = true;          // required for the elevation verb
            psi.Verb = "runas";
            psi.WindowStyle = ProcessWindowStyle.Hidden;
            psi.WorkingDirectory = Path.GetDirectoryName(script);

            btnInstall.Enabled = btnRestore.Enabled = false;
            Log("");
            Log("Running as administrator - the output appears when it finishes.");
            Process proc;
            try
            {
                proc = Process.Start(psi);
            }
            catch (Exception ex)
            {
                // 1223 is the user dismissing the UAC prompt: not an error
                Log(ex is System.ComponentModel.Win32Exception
                    && ((System.ComponentModel.Win32Exception)ex).NativeErrorCode == 1223
                    ? "Cancelled - nothing was changed."
                    : "Could not start it as administrator: " + ex.Message);
                btnInstall.Enabled = btnRestore.Enabled = true;
                return;
            }
            proc.EnableRaisingEvents = true;
            proc.Exited += delegate
            {
                int code = proc.ExitCode;
                string text = "";
                try
                {
                    if (File.Exists(log))
                        text = File.ReadAllText(log, new UTF8Encoding(false));
                }
                catch (Exception ex) { text = "(could not read the output: " + ex.Message + ")"; }
                BeginInvoke((MethodInvoker)delegate
                {
                    foreach (string line in text.Replace("\r\n", "\n").Split('\n'))
                        if (line.Length > 0) Log(line);
                    Log("");
                    Log(code == 0 ? "Finished." : "Failed (exit code " + code + ").");
                    btnInstall.Enabled = btnRestore.Enabled = true;
                    StartExeCheck();
                    try { if (File.Exists(log)) File.Delete(log); }
                    catch { }
                });
            };
        }

        private bool CommonArgs(List<string> argv)
        {
            if (txtExePath.Text.Trim().Length == 0)
            {
                MessageBox.Show("Select the game executable first.", "No executable",
                                MessageBoxButtons.OK, MessageBoxIcon.Warning);
                return false;
            }
            int w, h;
            if (!int.TryParse(txtWidth.Text.Trim(), out w) ||
                !int.TryParse(txtHeight.Text.Trim(), out h) || w <= 0 || h <= 0)
            {
                MessageBox.Show("Enter a valid resolution.", "Invalid resolution",
                                MessageBoxButtons.OK, MessageBoxIcon.Warning);
                return false;
            }
            argv.Add("--exe");
            argv.Add("\"" + txtExePath.Text.Trim() + "\"");
            argv.Add("--width");
            argv.Add(w.ToString());
            argv.Add("--height");
            argv.Add(h.ToString());
            argv.Add("--yes");
            return true;
        }

        private void OnInstall(object sender, EventArgs e)
        {
            List<string> argv = new List<string>();
            if (!CommonArgs(argv)) return;
            if (!chkExe.Checked && !chkGameFiles.Checked &&
                !chkChromatic.Checked && !chkSharpen.Checked)
            {
                MessageBox.Show("Nothing is selected.", "Nothing to do",
                                MessageBoxButtons.OK, MessageBoxIcon.Information);
                return;
            }
            if (!chkExe.Checked) argv.Add("--no-exe");
            if (!chkGameFiles.Checked) argv.Add("--no-game-files");
            if (!chkChromatic.Checked) argv.Add("--no-chromatic-fix");
            if (chkSharpen.Checked) argv.Add("--sharpen");
            Run(argv);
        }

        private void OnRestore(object sender, EventArgs e)
        {
            List<string> argv = new List<string>();
            if (!CommonArgs(argv)) return;
            argv.Add("--restore");
            Run(argv);
        }

